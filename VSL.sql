DROP TABLE IF EXISTS quiz_attempts CASCADE;
DROP TABLE IF EXISTS practice_attempts CASCADE;
DROP TABLE IF EXISTS learning_progress CASCADE;
DROP TABLE IF EXISTS signs CASCADE;
DROP TABLE IF EXISTS lessons CASCADE;
DROP TABLE IF EXISTS topics CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ============================================================================
-- 2. TẠO CÁC BẢNG (TABLE DEFINITIONS)
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Bảng: USERS (Người dùng & Quản trị viên)
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    user_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        VARCHAR(100) NOT NULL,
    email            VARCHAR(255) NOT NULL UNIQUE,
    password_hash    VARCHAR(255) NOT NULL,
    phone            VARCHAR(20),
    avatar_url       VARCHAR(500),
    role             VARCHAR(20) NOT NULL DEFAULT 'STUDENT',
    xp               INT NOT NULL DEFAULT 0,
    level            INT NOT NULL DEFAULT 1,
    streak_days      INT NOT NULL DEFAULT 0,
    status           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(100),
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    updated_by       VARCHAR(100)
);

CREATE INDEX idx_users_email ON users(email);

-- ----------------------------------------------------------------------------
-- Bảng: TOPICS (Chủ đề học ngôn ngữ ký hiệu)
-- ----------------------------------------------------------------------------
CREATE TABLE topics (
    topic_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(150) NOT NULL,
    emoji            VARCHAR(10),
    level            VARCHAR(20),
    category         VARCHAR(30),
    description      VARCHAR(500),
    display_order    INT,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(100),
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    updated_by       VARCHAR(100)
);

CREATE INDEX idx_topics_display_order ON topics(display_order);

-- ----------------------------------------------------------------------------
-- Bảng: LESSONS (Bài học nằm trong chủ đề)
-- ----------------------------------------------------------------------------
CREATE TABLE lessons (
    lesson_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id          BIGINT NOT NULL REFERENCES topics(topic_id) ON DELETE CASCADE,
    title             VARCHAR(200) NOT NULL,
    description       VARCHAR(1000),
    objectives        VARCHAR(1000),
    video_url         VARCHAR(500),
    video_thumb       VARCHAR(500),
    duration          VARCHAR(10),
    difficulty        INT NOT NULL DEFAULT 1,
    estimated_minutes INT,
    display_order     INT,
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by        VARCHAR(100),
    updated_at        TIMESTAMP WITHOUT TIME ZONE,
    updated_by        VARCHAR(100)
);

CREATE INDEX idx_lessons_topic_order ON lessons(topic_id, display_order);

-- ----------------------------------------------------------------------------
-- Bảng: SIGNS (Ký hiệu cử chỉ bàn tay / từ vựng VSL)
-- ----------------------------------------------------------------------------
CREATE TABLE signs (
    sign_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id         BIGINT NOT NULL REFERENCES topics(topic_id) ON DELETE CASCADE,
    lesson_id        BIGINT REFERENCES lessons(lesson_id) ON DELETE SET NULL,
    display_order    INT,
    content_type     VARCHAR(20) NOT NULL DEFAULT 'sign',
    name_vi          VARCHAR(200) NOT NULL,
    duration         VARCHAR(10),
    video_url        VARCHAR(500),
    video_thumb      VARCHAR(500),
    description      VARCHAR(1000),
    steps_json       TEXT,
    cultural_note    VARCHAR(1000),
    difficulty       INT NOT NULL DEFAULT 1,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(100),
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    updated_by       VARCHAR(100)
);

CREATE INDEX idx_signs_topic ON signs(topic_id);
CREATE INDEX idx_signs_lesson_order ON signs(lesson_id, display_order);

-- ----------------------------------------------------------------------------
-- Bảng: LEARNING_PROGRESS (Tiến độ học tập của người dùng với từng ký hiệu)
-- ----------------------------------------------------------------------------
CREATE TABLE learning_progress (
    progress_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    sign_id          BIGINT NOT NULL REFERENCES signs(sign_id) ON DELETE CASCADE,
    status           VARCHAR(20) NOT NULL DEFAULT 'unlearned',
    mastery_score    NUMERIC(5, 2) DEFAULT 0.00,
    last_studied_at  TIMESTAMP WITHOUT TIME ZONE,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(100),
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    updated_by       VARCHAR(100),
    CONSTRAINT uq_learning_progress_user_sign UNIQUE (user_id, sign_id)
);

CREATE INDEX idx_learning_progress_user ON learning_progress(user_id);
CREATE INDEX idx_learning_progress_sign ON learning_progress(sign_id);

-- ----------------------------------------------------------------------------
-- Bảng: PRACTICE_ATTEMPTS (Lịch sử luyện tập camera / nhận diện AI)
-- ----------------------------------------------------------------------------
CREATE TABLE practice_attempts (
    practice_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    sign_id          BIGINT NOT NULL REFERENCES signs(sign_id) ON DELETE CASCADE,
    input_mode       VARCHAR(20) NOT NULL DEFAULT 'camera',
    predicted_label  VARCHAR(200),
    confidence       NUMERIC(6, 5),
    is_correct       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(100),
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    updated_by       VARCHAR(100)
);

CREATE INDEX idx_practice_attempts_user ON practice_attempts(user_id);
CREATE INDEX idx_practice_attempts_sign ON practice_attempts(sign_id);

-- ----------------------------------------------------------------------------
-- Bảng: QUIZ_ATTEMPTS (Lịch sử kiểm tra / làm quiz trắc nghiệm)
-- ----------------------------------------------------------------------------
CREATE TABLE quiz_attempts (
    attempt_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    topic_id         BIGINT REFERENCES topics(topic_id) ON DELETE SET NULL,
    score            NUMERIC(5, 2) DEFAULT 0.00,
    total_questions  INT NOT NULL DEFAULT 0,
    correct_answers  INT NOT NULL DEFAULT 0,
    started_at       TIMESTAMP WITHOUT TIME ZONE,
    completed_at     TIMESTAMP WITHOUT TIME ZONE,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(100),
    updated_at       TIMESTAMP WITHOUT TIME ZONE,
    updated_by       VARCHAR(100)
);

CREATE INDEX idx_quiz_attempts_user ON quiz_attempts(user_id);
CREATE INDEX idx_quiz_attempts_topic ON quiz_attempts(topic_id);


